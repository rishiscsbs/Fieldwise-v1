// Builds packages/shared/src/data/india.ts: a simplified outline of India for the SVG maps.
//
// Source: Natural Earth 1:10m Admin 0 countries, India point of view (public domain),
//   https://github.com/nvkelso/natural-earth-vector/blob/v5.1.2/geojson/ne_10m_admin_0_countries_ind.geojson
// The India point-of-view file shows the boundary as officially claimed by India; do not swap it for the
// default (de facto) Natural Earth file.
//
// Usage: node scripts/build-india-outline.mjs <path to ne_10m_admin_0_countries_ind.geojson>
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) throw new Error('Pass the path to ne_10m_admin_0_countries_ind.geojson');
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const TOLERANCE = 0.04; // degrees (~4 km)
const MIN_AREA = 0.0003; // square degrees; keeps Lakshadweep and the Andaman and Nicobar islands, drops rocks

const feature = JSON.parse(readFileSync(src, 'utf8')).features.find((f) => f.properties.ADM0_A3 === 'IND');
if (!feature) throw new Error('India not found');

/** Douglas–Peucker line simplification. */
function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  const [a, b] = [pts[0], pts.at(-1)];
  let max = 0;
  let idx = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const [x, y] = pts[i];
    const dx = b[0] - a[0];
    const dy = b[1] - a[1];
    const d = Math.abs(dy * x - dx * y + b[0] * a[1] - b[1] * a[0]) / (Math.hypot(dx, dy) || 1);
    if (d > max) {
      max = d;
      idx = i;
    }
  }
  if (max <= tol) return [a, b];
  return [...simplify(pts.slice(0, idx + 1), tol).slice(0, -1), ...simplify(pts.slice(idx), tol)];
}
/** Rings start and end on the same point, which defeats Douglas–Peucker; simplify the two halves separately. */
const simplifyRing = (ring, tol) => {
  const mid = Math.floor(ring.length / 2);
  return [...simplify(ring.slice(0, mid + 1), tol).slice(0, -1), ...simplify(ring.slice(mid), tol)];
};
const area = (ring) =>
  Math.abs(
    ring.reduce((s, [x, y], i) => {
      const [x2, y2] = ring[(i + 1) % ring.length];
      return s + x * y2 - x2 * y;
    }, 0),
  ) / 2;

const polygons = feature.geometry.coordinates
  .map((poly) => poly[0]) // outer rings only
  .filter((ring) => area(ring) >= MIN_AREA)
  .map((ring) =>
    simplifyRing(ring, TOLERANCE).map(([x, y]) => [Math.round(x * 100) / 100, Math.round(y * 100) / 100]),
  )
  .filter((ring) => ring.length >= 3);

const points = polygons.reduce((n, r) => n + r.length, 0);
const out = `/* Outline of India for the SVG maps, simplified from Natural Earth 1:10m (India point of view), public domain.
   Generated by scripts/build-india-outline.mjs; do not edit by hand. ${polygons.length} rings, ${points} points, [lon, lat]. */
export const INDIA_OUTLINE: [number, number][][] = ${JSON.stringify(polygons)};

/** Bounding box of the outline: [minLon, minLat, maxLon, maxLat] */
export const INDIA_BOUNDS: [number, number, number, number] = [68.1, 6.7, 97.4, 37.1];
`;
writeFileSync(join(root, 'packages/shared/src/data/india.ts'), out);
console.log(`Wrote india.ts: ${polygons.length} rings, ${points} points`);
